    [Fact]
    public void Test_UsesColumnToFindTheEnclosingType()
    {
        // A generated type and a hand-written type share a line. The finding is in the
        // hand-written type, so it must not be attributed to the generated one.
        const string content = """
            using System.CodeDom.Compiler;
            namespace N
            {
                [GeneratedCode("t","1")] class G { } class H { void M() { try {} catch {} } }
            }
            """;
        var tree = CSharpSyntaxTree.ParseText(content, path: "File.cs");

        var catchColumn = content.Split('\n')[3].IndexOf("catch", StringComparison.Ordinal) + 1;
        var result = CreateResult(lineNumber: 4, column: catchColumn);

        Assert.False(GeneratedCodeDetector.IsResultInGeneratedType(result, tree));
    }

