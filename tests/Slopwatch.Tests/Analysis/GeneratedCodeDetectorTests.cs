using Microsoft.CodeAnalysis.CSharp;
using Slopwatch.Analysis;
using Slopwatch.Detection;
using Xunit;

namespace Slopwatch.Tests.Analysis;

/// <summary>
/// Tests for <see cref="GeneratedCodeDetector"/>.
/// </summary>
public class GeneratedCodeDetectorTests
{
    [Theory]
    [InlineData("TemporaryGeneratedFile_abc123.cs")]
    [InlineData("Form1.Designer.cs")]
    [InlineData("Model.g.cs")]
    [InlineData("Model.g.i.cs")]
    [InlineData("Model.generated.cs")]
    [InlineData("model.DESIGNER.cs")]
    public void Test_DetectsGeneratedFileName(string fileName)
    {
        Assert.True(GeneratedCodeDetector.IsGeneratedFile(fileName));
    }

    [Theory]
    [InlineData("Program.cs")]
    [InlineData("Generated.cs")]
    [InlineData("Designer.cs")]
    [InlineData("Model.cs")]
    public void Test_DoesNotDetectHandWrittenFileName(string fileName)
    {
        Assert.False(GeneratedCodeDetector.IsGeneratedFile(fileName));
    }

    [Fact]
    public void Test_FileNameSuffixCheckIsExtensionAgnostic()
    {
        // Roslyn's IsGeneratedCodeFile checks the name without its extension, so any extension
        // following a generated suffix matches. Mirrored here for consistency.
        Assert.True(GeneratedCodeDetector.IsGeneratedFile("Model.g.txt"));
    }

    [Theory]
    [InlineData("// <auto-generated/>\nnamespace N { class C { } }")]
    [InlineData("// <autogenerated>\nnamespace N { class C { } }")]
    [InlineData("// <AUTO-GENERATED />\nnamespace N { class C { } }")]
    [InlineData("/* <auto-generated/> */\nnamespace N { class C { } }")]
    public void Test_DetectsAutoGeneratedHeader(string content)
    {
        var tree = CSharpSyntaxTree.ParseText(content, path: "File.cs");

        Assert.True(GeneratedCodeDetector.IsGeneratedFile("File.cs", content, tree));
    }

    [Fact]
    public void Test_DoesNotDetectHeaderInNonLeadingComment()
    {
        const string content = """
            namespace N
            {
                // <auto-generated/>
                class C { }
            }
            """;
        var tree = CSharpSyntaxTree.ParseText(content, path: "File.cs");

        Assert.False(GeneratedCodeDetector.IsGeneratedFile("File.cs", content, tree));
    }

    [Fact]
    public void Test_DoesNotDetectHeaderInStringLiteral()
    {
        const string content = """
            namespace N
            {
                class C
                {
                    const string Marker = "// <auto-generated/>";
                }
            }
            """;
        var tree = CSharpSyntaxTree.ParseText(content, path: "File.cs");

        Assert.False(GeneratedCodeDetector.IsGeneratedFile("File.cs", content, tree));
    }

    [Fact]
    public void Test_DetectsHeaderWithoutSyntaxTree()
    {
        const string content = "// <auto-generated/>\nnamespace N { class C { } }";

        Assert.True(GeneratedCodeDetector.IsGeneratedFile("File.cs", content, syntaxTree: null));
    }

    [Fact]
    public void Test_DetectsGeneratedCodeAttribute()
    {
        const string content = """
            using System.CodeDom.Compiler;

            namespace N
            {
                [GeneratedCode("tool", "1.0")]
                class C
                {
                    void M() { }
                }
            }
            """;
        var tree = CSharpSyntaxTree.ParseText(content, path: "File.cs");
        var result = CreateResult(lineNumber: 8);

        Assert.True(GeneratedCodeDetector.IsResultInGeneratedType(result, tree));
    }

    [Fact]
    public void Test_DetectsDebuggerNonUserCodeAttribute()
    {
        const string content = """
            using System.Diagnostics;

            namespace N
            {
                [DebuggerNonUserCode]
                class C
                {
                    void M() { }
                }
            }
            """;
        var tree = CSharpSyntaxTree.ParseText(content, path: "File.cs");
        var result = CreateResult(lineNumber: 8);

        Assert.True(GeneratedCodeDetector.IsResultInGeneratedType(result, tree));
    }

    [Fact]
    public void Test_DetectsFullyQualifiedGeneratedCodeAttribute()
    {
        const string content = """
            namespace N
            {
                [System.CodeDom.Compiler.GeneratedCode("tool", "1.0")]
                class C
                {
                    void M() { }
                }
            }
            """;
        var tree = CSharpSyntaxTree.ParseText(content, path: "File.cs");
        var result = CreateResult(lineNumber: 6);

        Assert.True(GeneratedCodeDetector.IsResultInGeneratedType(result, tree));
    }

    [Fact]
    public void Test_DoesNotDetectAttributeOnPartialType()
    {
        // Roslyn treats a partial type with multiple declarations as non-generated because the
        // attribute may live on a different declaration. Without a compilation we cannot resolve
        // that, so partial types are conservatively treated as hand-written.
        const string content = """
            using System.CodeDom.Compiler;

            namespace N
            {
                [GeneratedCode("tool", "1.0")]
                partial class C
                {
                    void M() { }
                }
            }
            """;
        var tree = CSharpSyntaxTree.ParseText(content, path: "File.cs");
        var result = CreateResult(lineNumber: 8);

        Assert.False(GeneratedCodeDetector.IsResultInGeneratedType(result, tree));
    }

    [Fact]
    public void Test_DoesNotDetectAttributeOnUnrelatedType()
    {
        const string content = """
            using System.CodeDom.Compiler;

            namespace N
            {
                [GeneratedCode("tool", "1.0")]
                class Generated { }

                class HandWritten
                {
                    void M() { }
                }
            }
            """;
        var tree = CSharpSyntaxTree.ParseText(content, path: "File.cs");
        var result = CreateResult(lineNumber: 10);

        Assert.False(GeneratedCodeDetector.IsResultInGeneratedType(result, tree));
    }

    [Fact]
    public void Test_DoesNotDetectWithoutSyntaxTree()
    {
        var result = CreateResult(lineNumber: 1);

        Assert.False(GeneratedCodeDetector.IsResultInGeneratedType(result, syntaxTree: null));
    }

    private static DetectionResult CreateResult(int lineNumber) => new(
        RuleId: "SW001",
        RuleName: "Test",
        Severity: DetectionSeverity.Warning,
        FilePath: "File.cs",
        LineNumber: lineNumber,
        Column: 1,
        Message: "test");
}
