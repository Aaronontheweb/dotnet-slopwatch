    [Fact]
    public void Test_HeaderMarkerIsCaseSensitive()
    {
        // Roslyn's comparison is ordinal, so an uppercase marker is not a generated header.
        const string content = "// <AUTO-GENERATED />\nnamespace N { class C { } }";
        var tree = CSharpSyntaxTree.ParseText(content, path: "File.cs");

        Assert.False(GeneratedCodeDetector.IsGeneratedFile("File.cs", content, tree));
    }

    [Fact]
    public void Test_RazorMarkupTextIsNotTreatedAsGeneratedHeader()
    {
        // The marker appears as markup text inside <pre>, not as a Razor comment.
        const string content = """
            <pre>
            // <auto-generated/>
            </pre>
            @{ try { throw new System.Exception(); } catch {} }
            """;

        Assert.False(GeneratedCodeDetector.IsGeneratedFile("Component.razor", content, syntaxTree: null));
    }

    [Fact]
    public void Test_RazorStringLiteralContainingMarkerIsNotGenerated()
    {
        // The marker appears inside a C# string literal, not a Razor comment.
        const string content = """
            @{ var example = "@* <auto-generated/> *@"; try {} catch {} }
            """;

        Assert.False(GeneratedCodeDetector.IsGeneratedFile("Component.razor", content, syntaxTree: null));
    }

    [Fact]
    public void Test_RazorCommentAfterMarkupIsNotGenerated()
    {
        // A comment mentioning the marker after page content is not a leading header.
        const string content = """
            <h1>Hand-written page</h1>
            @* <auto-generated/> *@
            """;

        Assert.False(GeneratedCodeDetector.IsGeneratedFile("Component.razor", content, syntaxTree: null));
    }

    [Fact]
    public void Test_RazorCommentWithMarkerIsDetected()
    {
        const string content = """
            @* <auto-generated/> *@
            @code { private void M() { } }
            """;

        Assert.True(GeneratedCodeDetector.IsGeneratedFile("Component.razor", content, syntaxTree: null));
    }

    private static DetectionResult CreateResult(int lineNumber, int column = 1) => new(
        RuleId: "SW001",
        RuleName: "Test",
        Severity: DetectionSeverity.Warning,
        FilePath: "File.cs",
        LineNumber: lineNumber,
        Column: column,
        Message: "test");
