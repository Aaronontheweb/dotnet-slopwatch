    [Fact]
    public async Task Test_RecordsSkippedGeneratedFiles()
    {
        var (dir, file) = await CreateTempFileAsync(
            "Generated.cs",
            "// <auto-generated/>\n" + SloppyCode);

        try
        {
            var analyzer = CreateAnalyzer(GeneratedCodeMode.Skip);
            await foreach (var _ in analyzer.AnalyzeFileAsync(file)) { }

            Assert.Contains(file, analyzer.SkippedGeneratedFiles);
        }
        finally
        {
            Directory.Delete(dir, true);
        }
    }

    [Fact]
    public async Task Test_DoesNotRecordSkippedFilesInAnalyzeMode()
    {
        var (dir, file) = await CreateTempFileAsync(
            "Generated.cs",
            "// <auto-generated/>\n" + SloppyCode);

        try
        {
            var analyzer = CreateAnalyzer(GeneratedCodeMode.Analyze);
            await foreach (var _ in analyzer.AnalyzeFileAsync(file)) { }

            Assert.Empty(analyzer.SkippedGeneratedFiles);
        }
        finally
        {
            Directory.Delete(dir, true);
        }
    }

    [Fact]
    public async Task Test_SkipsRazorFileWithGeneratedComment()
    {
        // A Razor comment carrying the marker is a genuine generated declaration.
        var (dir, file) = await CreateTempFileAsync(
            "Component.razor",
            """
            @* <auto-generated/> *@
            @code {
                private void M() { }
            }
            """);

        try
        {
            var analyzer = CreateAnalyzer(GeneratedCodeMode.Skip);
            await foreach (var _ in analyzer.AnalyzeFileAsync(file)) { }

            Assert.Contains(file, analyzer.SkippedGeneratedFiles);
        }
        finally
        {
            Directory.Delete(dir, true);
        }
    }

    [Fact]
    public async Task Test_DoesNotSkipRazorFileWithMarkerAsMarkupText()
    {
        // The marker appears as markup text inside <pre>, not as a Razor comment, so the file
        // must still be analyzed.
        var (dir, file) = await CreateTempFileAsync(
            "Component.razor",
            """
            <pre>
            // <auto-generated/>
            </pre>
            @code {
                private void M() { }
            }
            """);

        try
        {
            var analyzer = CreateAnalyzer(GeneratedCodeMode.Skip);
            await foreach (var _ in analyzer.AnalyzeFileAsync(file)) { }

            Assert.Empty(analyzer.SkippedGeneratedFiles);
        }
        finally
        {
            Directory.Delete(dir, true);
        }
    }

    [Fact]
    public async Task Test_AttributeDetectionCanBeDisabled()
    {
        // The cross-file shadowing limitation cannot be resolved from a single syntax tree, so
        // the attribute check is opt-out.
        var (dir, file) = await CreateTempFileAsync(
            "Mixed.cs",
            """
            using System.CodeDom.Compiler;
            using Xunit;

            namespace N
            {
                [GeneratedCode("tool", "1.0")]
                public class GeneratedTests
                {
                    [Fact(Skip = "Broken test")]
                    public void BrokenTest() { }
                }
            }
            """);

        try
        {
            var analyzer = new FileAnalyzer(
                new IDetectionRule[] { new DisabledTestRule() },
                new AnalysisOptions
                {
                    GeneratedCodeMode = GeneratedCodeMode.Skip,
                    DetectGeneratedCodeAttributes = false,
                    TestFilePatterns = new[] { "**/*.cs" }
                });

            var results = new List<DetectionResult>();
            await foreach (var result in analyzer.AnalyzeFileAsync(file))
            {
                results.Add(result);
            }

            Assert.Single(results);
        }
        finally
        {
            Directory.Delete(dir, true);
        }
    }

    [Fact]
    public async Task Test_AnalyzeModeReachesGeneratedFileName()
    {
        // The default exclude patterns must not short-circuit the generated-code mode, otherwise
        // analyze mode can never reach these files.
        var (dir, file) = await CreateTempFileAsync("Model.g.cs", SloppyCode);

        try
        {
            var results = await AnalyzeAsync(file, GeneratedCodeMode.Analyze);

            Assert.Single(results);
        }
        finally
        {
            Directory.Delete(dir, true);
        }
    }

    [Fact]
    public async Task Test_DefaultExcludesDoNotContainGeneratedFilePatterns()
    {
        var options = new AnalysisOptions();

        Assert.DoesNotContain("**/*.g.cs", options.ExcludePatterns);
        Assert.DoesNotContain("**/*.g.i.cs", options.ExcludePatterns);
        Assert.DoesNotContain("**/*.Designer.cs", options.ExcludePatterns);
        Assert.DoesNotContain("**/*.generated.cs", options.ExcludePatterns);
    }

    [Fact]
    public async Task Test_AttributeDetectionIsOffByDefault()
    {
        var (dir, file) = await CreateTempFileAsync(
            "Mixed.cs",
            """
            using System.CodeDom.Compiler;
            using Xunit;

            namespace N
            {
                [GeneratedCode("tool", "1.0")]
                public class GeneratedTests
                {
                    [Fact(Skip = "Broken test")]
                    public void BrokenTest() { }
                }
            }
            """);

        try
        {
            // Default options: attribute detection is opt-in, so the finding is reported.
            var analyzer = new FileAnalyzer(
                new IDetectionRule[] { new DisabledTestRule() },
                new AnalysisOptions { TestFilePatterns = new[] { "**/*.cs" } });

            var results = new List<DetectionResult>();
            await foreach (var result in analyzer.AnalyzeFileAsync(file))
            {
                results.Add(result);
            }

            Assert.Single(results);
        }
        finally
        {
            Directory.Delete(dir, true);
        }
    }

    private static FileAnalyzer CreateAnalyzer(GeneratedCodeMode mode) => new(
        new IDetectionRule[] { new DisabledTestRule() },
        new AnalysisOptions
        {
            GeneratedCodeMode = mode,
            DetectGeneratedCodeAttributes = true,
            TestFilePatterns = new[] { "**/*.cs" }
        });

    private static async Task<List<DetectionResult>> AnalyzeAsync(string file, GeneratedCodeMode mode)
    {
        var analyzer = CreateAnalyzer(mode);
        var results = new List<DetectionResult>();

        await foreach (var result in analyzer.AnalyzeFileAsync(file))
        {
            results.Add(result);
        }

        return results;
    }

    private static async Task<(string dir, string file)> CreateTempFileAsync(string fileName, string content)
    {
        var dir = Path.Combine(Path.GetTempPath(), Guid.NewGuid().ToString());
        Directory.CreateDirectory(dir);
        var file = Path.Combine(dir, fileName);
        await File.WriteAllTextAsync(file, content);
        return (dir, file);
    }
}
