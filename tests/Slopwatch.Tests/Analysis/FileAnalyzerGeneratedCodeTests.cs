using Slopwatch.Analysis;
using Slopwatch.Detection;
using Slopwatch.Detection.Rules;
using Xunit;

namespace Slopwatch.Tests.Analysis;

/// <summary>
/// Tests for generated-code handling in <see cref="FileAnalyzer"/>.
/// </summary>
public class FileAnalyzerGeneratedCodeTests
{
    private const string SloppyCode = """
        using Xunit;
        public class TestClass
        {
            [Fact(Skip = "Broken test")]
            public void BrokenTest() { }
        }
        """;

    [Fact]
    public async Task Test_SkipsFileWithAutoGeneratedHeader()
    {
        var (dir, file) = await CreateTempFileAsync(
            "Generated.cs",
            "// <auto-generated/>\n" + SloppyCode);

        try
        {
            var results = await AnalyzeAsync(file, GeneratedCodeMode.Skip);

            Assert.Empty(results);
        }
        finally
        {
            Directory.Delete(dir, true);
        }
    }

    [Fact]
    public async Task Test_SkipsFileWithGeneratedFileName()
    {
        var (dir, file) = await CreateTempFileAsync("Model.g.cs", SloppyCode);

        try
        {
            var results = await AnalyzeAsync(file, GeneratedCodeMode.Skip);

            Assert.Empty(results);
        }
        finally
        {
            Directory.Delete(dir, true);
        }
    }

    [Fact]
    public async Task Test_SkipsTypeWithGeneratedCodeAttribute()
