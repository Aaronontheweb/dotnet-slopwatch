using Slopwatch.Analysis;
using Slopwatch.Detection;
using Slopwatch.Detection.Rules;
using Xunit;

namespace Slopwatch.Tests.Analysis;

/// <summary>
/// Tests for generated-code handling in <see cref="FileAnalyzer"/>.
/// </summary>
public class FileAnalyzerGeneratedCodeTests
{
    private const string SloppyCode = """
        using Xunit;
        public class TestClass
        {
            [Fact(Skip = "Broken test")]
            public void BrokenTest() { }
        }
        """;

    [Fact]
    public async Task Test_SkipsFileWithAutoGeneratedHeader()
    {
        var (dir, file) = await CreateTempFileAsync(
            "Generated.cs",
            "// <auto-generated/>\n" + SloppyCode);

        try
        {
            var results = await AnalyzeAsync(file, GeneratedCodeMode.Skip);

            Assert.Empty(results);
        }
        finally
        {
            Directory.Delete(dir, true);
        }
    }

    [Fact]
    public async Task Test_SkipsFileWithGeneratedFileName()
    {
        var (dir, file) = await CreateTempFileAsync("Model.g.cs", SloppyCode);

        try
        {
            var results = await AnalyzeAsync(file, GeneratedCodeMode.Skip);

            Assert.Empty(results);
        }
        finally
        {
            Directory.Delete(dir, true);
        }
    }

    [Fact]
    public async Task Test_SkipsTypeWithGeneratedCodeAttribute()
    {
        var (dir, file) = await CreateTempFileAsync(
            "Mixed.cs",
            """
            using System.CodeDom.Compiler;
            using Xunit;

            namespace N
            {
                [GeneratedCode("tool", "1.0")]
                public class GeneratedTests
                {
                    [Fact(Skip = "Broken test")]
                    public void BrokenTest() { }
                }
            }
            """);

        try
        {
            var results = await AnalyzeAsync(file, GeneratedCodeMode.Skip);

            Assert.Empty(results);
        }
        finally
        {
            Directory.Delete(dir, true);
        }
    }

    [Fact]
    public async Task Test_AnalyzesHandWrittenTypeInMixedFile()
    {
        var (dir, file) = await CreateTempFileAsync(
            "Mixed.cs",
            """
            using System.CodeDom.Compiler;
            using Xunit;

            namespace N
            {
                [GeneratedCode("tool", "1.0")]
                public class GeneratedTests
                {
                    [Fact(Skip = "Broken test")]
                    public void GeneratedBrokenTest() { }
                }

                public class HandWrittenTests
                {
                    [Fact(Skip = "Broken test")]
                    public void HandWrittenBrokenTest() { }
                }
            }
            """);

        try
        {
            var results = await AnalyzeAsync(file, GeneratedCodeMode.Skip);

            var result = Assert.Single(results);
            Assert.Contains("HandWrittenBrokenTest", result.Message);
        }
        finally
        {
            Directory.Delete(dir, true);
        }
    }

    [Fact]
    public async Task Test_AnalyzeModeReportsGeneratedFindings()
    {
        var (dir, file) = await CreateTempFileAsync(
            "Generated.cs",
            "// <auto-generated/>\n" + SloppyCode);

        try
        {
            var results = await AnalyzeAsync(file, GeneratedCodeMode.Analyze);

            var result = Assert.Single(results);
            Assert.False(result.IsGeneratedCode);
        }
        finally
        {
            Directory.Delete(dir, true);
        }
    }

    [Fact]
    public async Task Test_AnalyzeAndReportModeMarksGeneratedFindings()
    {
        var (dir, file) = await CreateTempFileAsync(
            "Generated.cs",
            "// <auto-generated/>\n" + SloppyCode);

        try
        {
            var results = await AnalyzeAsync(file, GeneratedCodeMode.AnalyzeAndReport);

            var result = Assert.Single(results);
            Assert.True(result.IsGeneratedCode);
        }
        finally
        {
            Directory.Delete(dir, true);
        }
    }

    [Fact]
    public async Task Test_AnalyzeAndReportModeMarksAttributeGeneratedFindings()
    {
        var (dir, file) = await CreateTempFileAsync(
            "Mixed.cs",
            """
            using System.CodeDom.Compiler;
            using Xunit;

            namespace N
            {
                [GeneratedCode("tool", "1.0")]
                public class GeneratedTests
                {
                    [Fact(Skip = "Broken test")]
                    public void BrokenTest() { }
                }
            }
            """);

        try
        {
            var results = await AnalyzeAsync(file, GeneratedCodeMode.AnalyzeAndReport);

            var result = Assert.Single(results);
            Assert.True(result.IsGeneratedCode);
        }
        finally
        {
            Directory.Delete(dir, true);
        }
    }

    [Fact]
    public async Task Test_RecordsSkippedGeneratedFiles()
    {
        var (dir, file) = await CreateTempFileAsync(
            "Generated.cs",
            "// <auto-generated/>\n" + SloppyCode);

        try
        {
            var analyzer = CreateAnalyzer(GeneratedCodeMode.Skip);
            await foreach (var _ in analyzer.AnalyzeFileAsync(file)) { }

            Assert.Contains(file, analyzer.SkippedGeneratedFiles);
        }
        finally
        {
            Directory.Delete(dir, true);
        }
    }

    [Fact]
    public async Task Test_DoesNotRecordSkippedFilesInAnalyzeMode()
    {
        var (dir, file) = await CreateTempFileAsync(
            "Generated.cs",
            "// <auto-generated/>\n" + SloppyCode);

        try
        {
            var analyzer = CreateAnalyzer(GeneratedCodeMode.Analyze);
            await foreach (var _ in analyzer.AnalyzeFileAsync(file)) { }

            Assert.Empty(analyzer.SkippedGeneratedFiles);
        }
        finally
        {
            Directory.Delete(dir, true);
        }
    }

    [Fact]
    public async Task Test_DoesNotSkipRazorFileWithGeneratedMarker()
    {
        // Razor files produce a synthesized syntax tree; the header check must run against the
        // original markup, and the attribute check must not run against generated C#.
        var (dir, file) = await CreateTempFileAsync(
            "Component.razor",
            """
            @* <auto-generated/> *@
            @code {
                private void M() { }
            }
            """);

        try
        {
            var analyzer = CreateAnalyzer(GeneratedCodeMode.Skip);
            await foreach (var _ in analyzer.AnalyzeFileAsync(file)) { }

            Assert.Empty(analyzer.SkippedGeneratedFiles);
        }
        finally
        {
            Directory.Delete(dir, true);
        }
    }

    private static FileAnalyzer CreateAnalyzer(GeneratedCodeMode mode) => new(
        new IDetectionRule[] { new DisabledTestRule() },
        new AnalysisOptions
        {
            GeneratedCodeMode = mode,
            TestFilePatterns = new[] { "**/*.cs" }
        });

    private static async Task<List<DetectionResult>> AnalyzeAsync(string file, GeneratedCodeMode mode)
    {
        var analyzer = CreateAnalyzer(mode);
        var results = new List<DetectionResult>();

        await foreach (var result in analyzer.AnalyzeFileAsync(file))
        {
            results.Add(result);
        }

        return results;
    }

    private static async Task<(string dir, string file)> CreateTempFileAsync(string fileName, string content)
    {
        var dir = Path.Combine(Path.GetTempPath(), Guid.NewGuid().ToString());
        Directory.CreateDirectory(dir);
        var file = Path.Combine(dir, fileName);
        await File.WriteAllTextAsync(file, content);
        return (dir, file);
    }
}
