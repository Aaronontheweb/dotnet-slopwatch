using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.Extensions.FileSystemGlobbing;
using Microsoft.Extensions.FileSystemGlobbing.Abstractions;
using Slopwatch.Detection;

namespace Slopwatch.Analysis;

/// <summary>
/// Main analysis engine for detecting code patterns across files.
/// </summary>
/// <remarks>
/// The FileAnalyzer orchestrates the analysis process by:
/// 1. Reading file content
/// 2. Determining file type and context (e.g., test files)
/// 3. Creating DetectionContext objects
/// 4. Running applicable rules
/// 5. Collecting and filtering results based on options
/// </remarks>
public sealed class FileAnalyzer
{
    private readonly RuleRegistry _ruleRegistry;
    private readonly AnalysisOptions _options;
    private readonly System.Collections.Concurrent.ConcurrentDictionary<string, byte> _skippedGeneratedFiles =
        new(StringComparer.OrdinalIgnoreCase);

    /// <summary>
    /// Gets the paths of files skipped entirely because they declare themselves generated.
    /// </summary>
    /// <remarks>
    /// Baseline synchronization uses this to avoid pruning entries for files that were
    /// present in the scan but deliberately not analyzed.
    /// </remarks>
    public IReadOnlyCollection<string> SkippedGeneratedFiles => _skippedGeneratedFiles.Keys.ToList();

    /// <summary>
    /// Initializes a new instance of the <see cref="FileAnalyzer"/> class.
    /// </summary>
    /// <param name="rules">The collection of detection rules to use for analysis.</param>
    /// <param name="options">The analysis options to configure behavior. If null, default options are used.</param>
    /// <exception cref="ArgumentNullException">Thrown if <paramref name="rules"/> is null.</exception>
    public FileAnalyzer(IEnumerable<IDetectionRule> rules, AnalysisOptions? options = null)
    {
        ArgumentNullException.ThrowIfNull(rules);

        _ruleRegistry = new RuleRegistry();
        _ruleRegistry.RegisterRules(rules);
        _options = options ?? new AnalysisOptions();
    }

    /// <summary>
    /// Analyzes a single file for code pattern violations.
    /// </summary>
    /// <param name="filePath">The path to the file to analyze.</param>
    /// <param name="cancellationToken">A token to monitor for cancellation requests.</param>
    /// <returns>An async enumerable of detection results.</returns>
    /// <exception cref="ArgumentException">Thrown if <paramref name="filePath"/> is null or whitespace.</exception>
    /// <exception cref="FileNotFoundException">Thrown if the specified file does not exist.</exception>
    public async IAsyncEnumerable<DetectionResult> AnalyzeFileAsync(
        string filePath,
        [System.Runtime.CompilerServices.EnumeratorCancellation] CancellationToken cancellationToken = default)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(filePath);

        if (!File.Exists(filePath))
        {
            throw new FileNotFoundException($"File not found: {filePath}", filePath);
        }

        // Check if file should be excluded
        if (ShouldExcludeFile(filePath))
        {
            yield break;
        }

        // Read file content
        var content = await File.ReadAllTextAsync(filePath, cancellationToken);

        // Create detection context
        var context = CreateDetectionContext(filePath, content);

        // Files with embedded C# (e.g. .razor, .cshtml) produce a syntax tree from
        // generated code. Track this so we can remap line numbers after rules run.
        var hasGeneratedSource = context.SyntaxTree is not null
            && !filePath.EndsWith(".cs", StringComparison.OrdinalIgnoreCase);

        // Generated-code handling. Filename and header checks are cheap and gate the whole file;
        // the [GeneratedCode] attribute is per-type, so it is applied to individual results below.
        // For embedded-C# files the syntax tree is synthesized by the Razor compiler and always
        // carries an <auto-generated> header, so the header check must read the original markup.
        var isGeneratedFile = _options.GeneratedCodeMode != GeneratedCodeMode.Analyze
            && GeneratedCodeDetector.IsGeneratedFile(
                filePath,
                content,
                hasGeneratedSource ? null : context.SyntaxTree);

        if (isGeneratedFile && _options.GeneratedCodeMode == GeneratedCodeMode.Skip)
        {
            _skippedGeneratedFiles.TryAdd(filePath, 0);
            yield break;
        }

        // For files that contain embedded C#, look up rules using the effective
        // analysis type so all C# rules apply automatically.
        var ruleMatchPath = hasGeneratedSource
            ? Path.ChangeExtension(filePath, ".cs")
            : filePath;

        // Get applicable rules
        var rules = _ruleRegistry.GetRulesForFile(ruleMatchPath);

        // Filter rules based on options
        var enabledRules = rules.Where(r => _options.IsRuleEnabled(r.RuleId)).ToList();

        if (enabledRules.Count == 0)
        {
            yield break;
        }

        // Run all applicable rules and yield results
        await foreach (var result in RunRulesAsync(enabledRules, context, cancellationToken))
        {
            // Filter by minimum severity
            if (result.Severity < _options.MinimumSeverity)
            {
                continue;
            }

            // For generated sources, remap line numbers from the generated C#
            // back to the original file using #line directive mappings.
            var mapped = hasGeneratedSource
                ? RemapLineNumber(result, context.SyntaxTree!)
                : result;

            // The [GeneratedCode] attribute is per-type, so it is evaluated per result rather
            // than gating the whole file. Razor files are excluded: their syntax tree is
            // synthesized from the markup, so attribute checks would not reflect the source.
            var isGeneratedResult = isGeneratedFile
                || (_options.DetectGeneratedCodeAttributes
                    && !hasGeneratedSource
                    && GeneratedCodeDetector.IsResultInGeneratedType(mapped, context.SyntaxTree));

            if (isGeneratedResult)
            {
                if (_options.GeneratedCodeMode == GeneratedCodeMode.Skip)
                {
                    // The file is still analyzed for its hand-written types, so it is not
                    // recorded as a whole-file skip. Baseline entries for filtered findings are
                    // pruned normally: the hash cannot distinguish identical snippets, and
                    // preserving them could shield a stale hand-written entry.
                    continue;
                }

                if (_options.GeneratedCodeMode == GeneratedCodeMode.AnalyzeAndReport)
                {
                    mapped = mapped with { IsGeneratedCode = true };
                }
            }

            yield return mapped;
        }
    }

    /// <summary>
    /// Analyzes multiple files for code pattern violations.
    /// </summary>
    /// <param name="filePaths">The paths to the files to analyze.</param>
    /// <param name="cancellationToken">A token to monitor for cancellation requests.</param>
    /// <returns>An async enumerable of detection results.</returns>
    /// <exception cref="ArgumentNullException">Thrown if <paramref name="filePaths"/> is null.</exception>
    public async IAsyncEnumerable<DetectionResult> AnalyzeFilesAsync(
        IEnumerable<string> filePaths,
        [System.Runtime.CompilerServices.EnumeratorCancellation] CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(filePaths);

        foreach (var filePath in filePaths)
        {
            cancellationToken.ThrowIfCancellationRequested();

            // Skip files that don't exist or encounter errors
            await foreach (var result in AnalyzeFileAsync(filePath, cancellationToken))
            {
                yield return result;
            }
        }
    }

    /// <summary>
    /// Analyzes all files in a directory matching the specified patterns.
    /// </summary>
    /// <param name="directoryPath">The directory path to search.</param>
    /// <param name="patterns">
    /// The glob patterns to match files against (e.g., "*.cs", "**/*.csproj").
    /// If null or empty, defaults to ["**/*"].
    /// </param>
    /// <param name="cancellationToken">A token to monitor for cancellation requests.</param>
    /// <returns>An async enumerable of detection results.</returns>
    /// <exception cref="ArgumentException">Thrown if <paramref name="directoryPath"/> is null or whitespace.</exception>
    /// <exception cref="DirectoryNotFoundException">Thrown if the specified directory does not exist.</exception>
    public async IAsyncEnumerable<DetectionResult> AnalyzeDirectoryAsync(
        string directoryPath,
        string[]? patterns = null,
        [System.Runtime.CompilerServices.EnumeratorCancellation] CancellationToken cancellationToken = default)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(directoryPath);

        if (!Directory.Exists(directoryPath))
        {
            throw new DirectoryNotFoundException($"Directory not found: {directoryPath}");
        }

        // Get all matching files
        var files = GetMatchingFiles(directoryPath, patterns ?? new[] { "**/*" });

        // Analyze each file
        await foreach (var result in AnalyzeFilesAsync(files, cancellationToken))
        {
            yield return result;
        }
    }

    /// <summary>
    /// Gets all files in a directory matching the specified patterns.
    /// </summary>
    /// <param name="directoryPath">The directory to search.</param>
    /// <param name="patterns">The glob patterns to match.</param>
    /// <returns>A collection of matching file paths.</returns>
    public IEnumerable<string> GetMatchingFiles(string directoryPath, string[] patterns)
    {
        var matcher = new Matcher(StringComparison.OrdinalIgnoreCase);

        // Add include patterns
        foreach (var pattern in patterns)
        {
            matcher.AddInclude(pattern);
        }

        // Add exclude patterns from options
        foreach (var excludePattern in _options.ExcludePatterns)
        {
            matcher.AddExclude(excludePattern);
        }

        var result = matcher.Execute(new DirectoryInfoWrapper(new DirectoryInfo(directoryPath)));

        return result.Files
            .Select(f => Path.Combine(directoryPath, f.Path))
            .Where(file => !IsInsideNestedWorktree(file, directoryPath));
    }

    /// <summary>
    /// Determines whether a file lives inside a git worktree nested below the analysis root.
    /// </summary>
    /// <param name="filePath">The full path to the file.</param>
    /// <param name="rootDirectory">The directory analysis started from.</param>
    /// <returns>True if the file is inside a nested worktree; otherwise, false.</returns>
    /// <remarks>
    /// A linked worktree is identified by a <c>.git</c> FILE whose gitdir pointer resolves to
    /// <c>&lt;common-dir&gt;/worktrees/&lt;name&gt;</c>. The main checkout has a <c>.git</c>
    /// directory, so it is never treated as nested. This replaces a name-based
    /// <c>**/worktrees/**</c> exclude, which skipped any directory that happened to be called
    /// <c>worktrees</c> — including ordinary source — and reported a clean scan for code it never
    /// read.
    /// <para>
    /// A <c>.git</c> file alone is not proof of a worktree: submodules
    /// (<c>&lt;super&gt;/.git/modules/&lt;name&gt;</c>) and checkouts made with
    /// <c>git init --separate-git-dir</c> also use gitfiles, and their source is distinct code
    /// that must still be analyzed. Unreadable or malformed gitfiles are treated as not-a-worktree
    /// so the failure mode is analyzing too much rather than silently skipping real source.
    /// </para>
    /// </remarks>
    private static bool IsInsideNestedWorktree(string filePath, string rootDirectory)
    {
        var root = TrimTrailingSeparators(Path.GetFullPath(rootDirectory));
        var directory = Path.GetDirectoryName(Path.GetFullPath(filePath));

        while (directory is not null)
        {
            var current = TrimTrailingSeparators(directory);

            // Stop at the analysis root (its own marker is never "nested") and at any path that
            // is not a strict descendant. Parent-directory include patterns such as
            // "../sibling/*.cs" match files outside the root; those are not nested worktrees.
            if (!IsStrictDescendant(current, root))
                return false;

            if (IsLinkedWorktreeMarker(Path.Combine(current, ".git")))
                return true;

            directory = Path.GetDirectoryName(current);
        }

        return false;
    }

    /// <summary>
    /// Determines whether a <c>.git</c> entry is a linked-worktree marker.
    /// </summary>
    /// <param name="gitEntryPath">The path to the candidate <c>.git</c> entry.</param>
    /// <returns>True if the entry is a gitfile pointing at a worktree gitdir; otherwise, false.</returns>
    /// <remarks>
    /// The directory name is not a reliable discriminator. A submodule added with
    /// <c>--name worktrees/lib</c> and a checkout made with
    /// <c>git init --separate-git-dir .../worktrees/checkout</c> both produce gitdirs whose
    /// parent is named <c>worktrees</c>, yet neither is a linked worktree.
    /// <para>
    /// Git's administrative layout is the reliable signal. Only a linked worktree's gitdir
    /// carries both a <c>commondir</c> file (pointing at the shared common dir) and a
    /// <c>gitdir</c> file (pointing back at this worktree's <c>.git</c> file). Submodule and
    /// separate-git-dir administrative directories carry neither.
    /// </para>
    /// </remarks>
    private static bool IsLinkedWorktreeMarker(string gitEntryPath)
    {
        // File.Exists is false for a directory, so a main checkout's .git directory is rejected here.
        if (!File.Exists(gitEntryPath))
            return false;

        string? gitDir;
        try
        {
            gitDir = ReadGitDirPointer(gitEntryPath);
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException
            or ArgumentException or NotSupportedException)
        {
            // Unreadable or malformed: analyze the file rather than silently skipping it.
            return false;
        }

        if (gitDir is null)
            return false;

        var commonDirFile = Path.Combine(gitDir, "commondir");
        var backPointerFile = Path.Combine(gitDir, "gitdir");

        // A nonexistent or unrelated gitdir has neither file, so a stale pointer cannot hide source.
        if (!File.Exists(commonDirFile) || !File.Exists(backPointerFile))
            return false;

        // Require the reciprocal pointer to name this .git file, so an administrative directory
        // belonging to some other checkout cannot suppress analysis here.
        try
        {
            var backPointer = File.ReadAllText(backPointerFile).Trim();
            if (backPointer.Length == 0)
                return false;

            var resolvedBack = Path.IsPathRooted(backPointer)
                ? Path.GetFullPath(backPointer)
                : Path.GetFullPath(Path.Combine(gitDir, backPointer));

            return string.Equals(
                TrimTrailingSeparators(resolvedBack),
                TrimTrailingSeparators(Path.GetFullPath(gitEntryPath)),
                PathComparison);
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException
            or ArgumentException or NotSupportedException)
        {
            return false;
        }
    }

    /// <summary>
    /// Reads the gitdir pointer from a <c>.git</c> file.
    /// </summary>
    /// <param name="gitEntryPath">The path to the <c>.git</c> file.</param>
    /// <returns>The absolute gitdir path, or null if the file is not a valid gitfile.</returns>
    private static string? ReadGitDirPointer(string gitEntryPath)
    {
        const string Prefix = "gitdir:";

        string? line;
        using (var reader = new StreamReader(gitEntryPath))
        {
            line = reader.ReadLine();
        }

        if (line is null || !line.StartsWith(Prefix, StringComparison.Ordinal))
            return null;

        var pointer = line.Substring(Prefix.Length).Trim();
        if (pointer.Length == 0)
            return null;

        // Relative pointers (git worktree --relative-paths) resolve against the .git file's directory.
        var baseDirectory = Path.GetDirectoryName(Path.GetFullPath(gitEntryPath));
        if (baseDirectory is null)
            return null;

        return Path.GetFullPath(Path.Combine(baseDirectory, pointer));
    }

    /// <summary>
    /// Determines whether a path is a strict descendant of a root directory.
    /// </summary>
    /// <param name="candidate">The candidate path.</param>
    /// <param name="root">The root directory.</param>
    /// <returns>True if <paramref name="candidate"/> is below <paramref name="root"/>.</returns>
    /// <remarks>
    /// A filesystem root (<c>/</c> or <c>C:\</c>) already ends in a separator, so the boundary
    /// character after it is the first character of the child name, not a separator. Comparing
    /// that character against a separator would reject every descendant of the root.
    /// </remarks>
    internal static bool IsStrictDescendant(string candidate, string root)
    {
        if (candidate.Length <= root.Length)
            return false;

        if (!candidate.StartsWith(root, PathComparison))
            return false;

        // The root already ends in a separator, so the prefix match alone proves containment.
        if (root[^1] == Path.DirectorySeparatorChar || root[^1] == Path.AltDirectorySeparatorChar)
            return true;

        // Require a separator boundary so "/repo-other" is not treated as living under "/repo".
        return candidate[root.Length] == Path.DirectorySeparatorChar
            || candidate[root.Length] == Path.AltDirectorySeparatorChar;
    }

    /// <summary>
    /// Removes trailing directory separators so path comparisons are not separator-sensitive.
    /// </summary>
    /// <param name="path">The path to trim.</param>
    /// <returns>The path without trailing separators, or the original path if it is a bare root.</returns>
    private static string TrimTrailingSeparators(string path)
    {
        var trimmed = path.TrimEnd(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar);
        return trimmed.Length == 0 ? path : trimmed;
    }

    /// <summary>
    /// Gets the comparison used for filesystem path equality on the current platform.
    /// </summary>
    private static StringComparison PathComparison =>
        OperatingSystem.IsWindows() ? StringComparison.OrdinalIgnoreCase : StringComparison.Ordinal;

    /// <summary>
    /// Creates a detection context for a file.
    /// </summary>
    /// <param name="filePath">The full path to the file.</param>
    /// <param name="content">The file content.</param>
    /// <returns>A detection context.</returns>
    private DetectionContext CreateDetectionContext(string filePath, string content)
    {
        var fileName = Path.GetFileName(filePath);
        var isTestFile = IsTestFile(filePath);

        // Parse C# files into syntax trees
        SyntaxTree? syntaxTree = null;
        if (filePath.EndsWith(".cs", StringComparison.OrdinalIgnoreCase))
        {
            try
            {
                syntaxTree = CSharpSyntaxTree.ParseText(content, path: filePath);
            }
            catch
            {
                // If parsing fails, continue without syntax tree
                // The content will still be available for text-based analysis
            }
        }
        else if (filePath.EndsWith(".razor", StringComparison.OrdinalIgnoreCase)
            || filePath.EndsWith(".cshtml", StringComparison.OrdinalIgnoreCase))
        {
            var generatedCSharp = RazorCodeExtractor.ExtractGeneratedCSharp(content, filePath);
            if (generatedCSharp is not null)
            {
                try
                {
                    syntaxTree = CSharpSyntaxTree.ParseText(generatedCSharp, path: filePath);
                }
                catch
                {
                    // If parsing fails, continue without syntax tree
                    syntaxTree = null;
                }
            }
        }

        return new DetectionContext(
            FilePath: filePath,
            FileName: fileName,
            Content: content,
            SyntaxTree: syntaxTree,
            IsTestFile: isTestFile);
    }

    /// <summary>
    /// Determines if a file is a test file based on configured patterns.
    /// </summary>
    /// <param name="filePath">The file path to check.</param>
    /// <returns>True if the file is a test file; otherwise, false.</returns>
    private bool IsTestFile(string filePath)
    {
        // Normalize the path to use forward slashes
        var normalizedPath = filePath.Replace('\\', '/');

        var matcher = new Matcher(StringComparison.OrdinalIgnoreCase);
        foreach (var pattern in _options.TestFilePatterns)
        {
            matcher.AddInclude(pattern);
        }

        // For absolute paths, match against the full path
        // For relative paths, match as-is
        // The Matcher.Match expects a relative path, so for absolute paths
        // we need to find the root and create a relative path from it
        string pathToMatch;
        if (Path.IsPathRooted(normalizedPath))
        {
            // For Unix-like paths starting with /, remove the leading slash
            // For Windows paths like C:\, we need to remove the drive letter
            if (normalizedPath.StartsWith('/'))
            {
                pathToMatch = normalizedPath.TrimStart('/');
            }
            else
            {
                // Windows path - get the path after the drive (e.g., C:/ -> rest of path)
                var pathRoot = Path.GetPathRoot(normalizedPath);
                if (!string.IsNullOrEmpty(pathRoot))
                {
                    pathToMatch = normalizedPath.Substring(pathRoot.Length).TrimStart('/').TrimStart('\\');
                }
                else
                {
                    pathToMatch = normalizedPath;
                }
            }
        }
        else
        {
            pathToMatch = normalizedPath;
        }

        var result = matcher.Match(pathToMatch);
        return result.HasMatches;
    }

    /// <summary>
    /// Determines if a file should be excluded from analysis.
    /// </summary>
    /// <param name="filePath">The file path to check.</param>
    /// <returns>True if the file should be excluded; otherwise, false.</returns>
    private bool ShouldExcludeFile(string filePath)
    {
        // Normalize the path to use forward slashes
        var normalizedPath = filePath.Replace('\\', '/');

        var matcher = new Matcher(StringComparison.OrdinalIgnoreCase);
        foreach (var pattern in _options.ExcludePatterns)
        {
            matcher.AddInclude(pattern);
        }

        // For absolute paths, match against the full path
        // For relative paths, match as-is
        string pathToMatch;
        if (Path.IsPathRooted(normalizedPath))
        {
            // For Unix-like paths starting with /, remove the leading slash
            // For Windows paths like C:\, we need to remove the drive letter
            if (normalizedPath.StartsWith('/'))
            {
                pathToMatch = normalizedPath.TrimStart('/');
            }
            else
            {
                // Windows path - get the path after the drive (e.g., C:/ -> rest of path)
                var pathRoot = Path.GetPathRoot(normalizedPath);
                if (!string.IsNullOrEmpty(pathRoot))
                {
                    pathToMatch = normalizedPath.Substring(pathRoot.Length).TrimStart('/').TrimStart('\\');
                }
                else
                {
                    pathToMatch = normalizedPath;
                }
            }
        }
        else
        {
            pathToMatch = normalizedPath;
        }

        var result = matcher.Match(pathToMatch);
        return result.HasMatches;
    }

    /// <summary>
    /// Runs all applicable rules against a detection context.
    /// </summary>
    /// <param name="rules">The rules to execute.</param>
    /// <param name="context">The detection context.</param>
    /// <param name="cancellationToken">A token to monitor for cancellation requests.</param>
    /// <returns>An async enumerable of detection results.</returns>
    private static async IAsyncEnumerable<DetectionResult> RunRulesAsync(
        IEnumerable<IDetectionRule> rules,
        DetectionContext context,
        [System.Runtime.CompilerServices.EnumeratorCancellation] CancellationToken cancellationToken)
    {
        foreach (var rule in rules)
        {
            cancellationToken.ThrowIfCancellationRequested();

            await foreach (var result in rule.AnalyzeAsync(context, cancellationToken))
            {
                yield return result;
            }
        }
    }

    /// <summary>
    /// Remaps a detection result's line number from generated code positions back to
    /// the original source file using #line directive mappings in the syntax tree.
    /// </summary>
    private static DetectionResult RemapLineNumber(DetectionResult result, SyntaxTree syntaxTree)
    {
        // The result's LineNumber is 1-based from GetLineSpan() in the generated code.
        // We need to find the corresponding position in the syntax tree and use
        // GetMappedLineSpan() to resolve the #line directives back to the original file.
        var generatedLine = result.LineNumber - 1; // 0-based for Roslyn
        var text = syntaxTree.GetText();

        if (generatedLine < 0 || generatedLine >= text.Lines.Count)
            return result;

        var position = text.Lines[generatedLine].Start;
        var mappedSpan = syntaxTree.GetMappedLineSpan(new Microsoft.CodeAnalysis.Text.TextSpan(position, 0));

        if (!mappedSpan.HasMappedPath && !mappedSpan.IsValid)
            return result;

        return result with
        {
            LineNumber = mappedSpan.StartLinePosition.Line + 1,
            Column = mappedSpan.StartLinePosition.Character + 1
        };
    }
}
